"""Write results/numbers.tex: one \\newcommand per number the paper may cite, each with its source.

Sources (all public benchmark output of the regimix repo):
  <results>/{fx,eq,m4}.json            main runs (arms, paired ours-minus-arm, diagnostics, api check)
  <results>/{fx,eq,m4}_variants.json   follow-up variants (variant-minus-arm)
  <results>/PRIVATE_LINE.txt           the one allowed sentence about the non-public task
  <preds>/<dataset>_test_logits.npz    held-out logits per arm and seed (recomputed paired SEs)

Two SEs per paired difference:
  *SE      the repo's own reported SE (JSON key paired_ours_minus_arm.se: moving-block bootstrap over time
           blocks for FX / equities, cluster bootstrap over series for M4, 2,000 draws, seed 0)
  *SER     recomputed here from the per-episode held-out logits with the same estimator (bench.core.stats.paired)
  *NaiveSE per-episode iid SE sd(d)/sqrt(n), shown only to say why it is not used (episodes share a path)

Usage: python results/make_numbers.py [--results DIR] [--preds DIR] [--out FILE]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np
from scipy.special import expit

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent  # the regimix repo root (paper/ lives inside it)
DS = {"Fx": ("fx", "eurusd_m1", "block"), "Eq": ("eq", "equities_daily", "block"), "Mf": ("m4", "m4_hourly", "cluster")}
ARMS = {"regimix": "Ours", "k1_pooled_probit": "Kone", "rv_probit": "Rv", "har_probit": "Har",
        "gate_ablation": "Gate", "logreg": "Logreg", "hgb": "Hgb", "hgb_plus_regime": "HgbReg", "k3": "Kthree",
        "nofloor_stock_em": "Stock", "next_step_off": "NextOff", "sigma_min_off": "SigOff", "drift_on": "DriftOn",
        "isotonic": "Iso", "platt_state": "PlattState"}
VARS = {"k4": "Kfour", "rv_relative_k2": "RvRelKtwo", "rv_relative_k3": "RvRelKthree",
        "har_relative_k2": "HarRelKtwo", "har_relative_k3": "HarRelKthree"}
WORD = {300: "Three", 1000: "Thousand", 3000: "ThreeThousand"}


class Out:
    def __init__(self):
        self.lines = ["% Generated by results/make_numbers.py. Do not edit by hand.",
                      "% Sign convention: paired values are ours - arm (or variant - arm); negative = ours better.", ""]

    def add(self, name, value, src):
        self.lines.append(f"% {src}")
        self.lines.append(f"\\newcommand{{\\n{name}}}{{{value}}}")


def f4(x):
    return f"{x:.4f}"


def sgn(x, nd=4):
    v = round(float(x), nd)
    return ("+" if v > 0 else "") + f"{v:.{nd}f}" if v != 0 else f"{0:.{nd}f}"


def lossvec(z, y):
    p = np.clip(expit(z), 1e-12, 1 - 1e-12)
    return -(y * np.log(p) + (1 - y) * np.log(1 - p))


def main_numbers(o, key, fname, js, npz, mode, paired):
    path = f"bench/results/{fname}.json"
    m = js["meta"]
    o.add(f"{key}NTest", f"{js['n_test']:,}", f"{path}: n_test")
    o.add(f"{key}NTrain", f"{js['n_train']:,}", f"{path}: n_train")
    o.add(f"{key}Seeds", len(js["seeds"]), f"{path}: len(seeds)")
    o.add(f"{key}Horizon", m["horizon"], f"{path}: meta.horizon (steps)")
    o.add(f"{key}PosRate", f"{m['pos_rate']:.3f}", f"{path}: meta.pos_rate")
    o.add(f"{key}WallMin", f"{js['wall_s'] / 60:.0f}", f"{path}: wall_s / 60")
    o.add(f"{key}ApiDiff", f"{js['api_check']['max_abs_logit_diff']:.1g}", f"{path}: api_check.max_abs_logit_diff")
    first = js["arms"]["k1_pooled_probit"]["paired_ours_minus_arm"]
    o.add(f"{key}NUnits", f"{first['n_units']:,}", f"{path}: arms.*.paired_ours_minus_arm.n_units")
    o.add(f"{key}SEMethod", first["method"], f"{path}: arms.*.paired_ours_minus_arm.method")
    y, blk = npz["y"], npz["block"]
    unit = blk // 1000 if mode == "cluster" else blk  # M4 block id = series * 1000 + day
    lo = {a: np.mean([lossvec(z, y) for z in npz[a]], axis=0) for a in npz.files if a not in ("y", "block")}
    for arm, code in ARMS.items():
        a = js["arms"][arm]
        src = f"{path}: arms.{arm}"
        o.add(f"{key}{code}LL", f4(a["logloss"]), f"{src}.logloss (mean over seeds of held-out log-loss, nats)")
        o.add(f"{key}{code}Brier", f4(a["brier"]), f"{src}.brier")
        o.add(f"{key}{code}ECE", f4(a["ece"]), f"{src}.ece (15 bins, mean over seeds)")
        o.add(f"{key}{code}SeedSd", f"{a['logloss_seed_sd']:.1e}", f"{src}.logloss_seed_sd")
        if arm in npz.files:
            pe = expit(npz[arm].mean(axis=0))
            idx = np.minimum((pe * 15).astype(int), 14)
            e = sum((idx == b).sum() * abs(pe[idx == b].mean() - y[idx == b].mean()) for b in range(15) if (idx == b).any())
            o.add(f"{key}{code}ECEens", f4(e / len(y)), "recomputed: ECE (15 bins) of the seed-averaged logit, as in Fig. 2")
        if arm == "regimix":
            continue
        p = a["paired_ours_minus_arm"]
        o.add(f"{key}{code}D", sgn(p["mean"]), f"{src}.paired_ours_minus_arm.mean (repo)")
        o.add(f"{key}{code}AbsD", f4(abs(p["mean"])), f"{src}.paired_ours_minus_arm.mean, absolute")
        o.add(f"{key}{code}SE", f4(p["se"]), f"{src}.paired_ours_minus_arm.se (repo-reported bootstrap SE)")
        o.add(f"{key}{code}Lo", sgn(p["ci95"][0]), f"{src}.paired_ours_minus_arm.ci95[0]")
        o.add(f"{key}{code}Hi", sgn(p["ci95"][1]), f"{src}.paired_ours_minus_arm.ci95[1]")
        if p.get("hac_se_block_means") is not None:
            o.add(f"{key}{code}HacSE", f4(p["hac_se_block_means"]), f"{src}.paired_ours_minus_arm.hac_se_block_means")
        d = lo["regimix"] - lo[arm]
        r = paired(d, blk, unit, mode=mode)
        o.add(f"{key}{code}SER", f4(r["se"]), f"recomputed from npz {arm} logits with bench.core.stats.paired ({mode})")
        o.add(f"{key}{code}NaiveSE", f4(d.std(ddof=1) / np.sqrt(len(d))), "recomputed: per-episode iid SE (not valid)")
        if abs(r["mean"] - p["mean"]) > 1e-9:
            raise AssertionError(f"{key} {arm}: recomputed mean {r['mean']} != repo {p['mean']}")
    s = js["arms"]["hgb_plus_regime"]["paired_stack_minus_hgb"]
    src = f"{path}: arms.hgb_plus_regime.paired_stack_minus_hgb"
    o.add(f"{key}StackD", sgn(s["mean"]), f"{src}.mean (boosting+regime - boosting; positive = appending hurt)")
    o.add(f"{key}StackSE", f4(s["se"]), f"{src}.se (repo)")
    o.add(f"{key}StackLo", sgn(s["ci95"][0]), f"{src}.ci95[0]")
    o.add(f"{key}StackHi", sgn(s["ci95"][1]), f"{src}.ci95[1]")
    r = paired(lo["hgb_plus_regime"] - lo["hgb"], blk, unit, mode=mode)
    o.add(f"{key}StackSER", f4(r["se"]), "recomputed from npz hgb_plus_regime - hgb logits (same estimator)")
    dg = js["diagnostics"]["k2"]
    src = f"{path}: diagnostics.k2"
    o.add(f"{key}DwellA", f"{dg['dwell'][0]:.1f}", f"{src}.dwell[0] (segments)")
    o.add(f"{key}DwellB", f"{dg['dwell'][1]:.1f}", f"{src}.dwell[1] (segments)")
    o.add(f"{key}SpreadRatio", f"{dg['spread_ratio']:.2f}", f"{src}.spread_ratio")
    o.add(f"{key}CollapseRatio", f"{dg['collapse_ratio']:.1f}", f"{src}.collapse_ratio (smallest var / min_covar)")
    o.add(f"{key}DistinctShare", f"{dg['posterior']['distinct_share']:.2f}", f"{src}.posterior.distinct_share")
    o.add(f"{key}NWarn", len(dg["warnings"]), f"{src}.warnings (count)")


def variant_numbers(o, key, fname, vj):
    path = f"bench/results/{fname}_variants.json"
    for row in vj["scaled"]:
        v = VARS[row["variant"]]
        o.add(f"{key}{v}LL", f4(row["logloss"]), f"{path}: scaled[{row['variant']}].logloss")
        for arm in ("regimix", "rv_probit", "har_probit", "k3"):
            if arm in row["vs"]:
                c = row["vs"][arm]
                o.add(f"{key}{v}Vs{ARMS[arm]}D", sgn(c["mean"]), f"{path}: scaled[{row['variant']}].vs.{arm}.mean")
                o.add(f"{key}{v}Vs{ARMS[arm]}SE", f4(c["se"]), f"{path}: scaled[{row['variant']}].vs.{arm}.se")
    for row in vj["small_n"]:
        n = WORD[row["n_train"]]
        for arm in ("rv_probit", "hgb", "k1_pooled_probit"):
            c = row["ours_minus"][arm]
            o.add(f"{key}Small{n}Vs{ARMS[arm]}D", sgn(c["mean"]), f"{path}: small_n[{row['n_train']}].ours_minus.{arm}.mean")
            o.add(f"{key}Small{n}Vs{ARMS[arm]}SE", f4(c["se"]), f"{path}: small_n[{row['n_train']}].ours_minus.{arm}.se")


def config_numbers(o, results: Path):
    """Setup constants the prose cites (defaults, lookbacks, offsets, counts), each read from its source."""
    import inspect

    from bench.core import stats
    from bench.data import equities, fx, m4
    from regimix import RegimeExceedanceClassifier

    sig = inspect.signature(RegimeExceedanceClassifier.__init__).parameters
    src = "regimix/estimator/classifier.py: RegimeExceedanceClassifier default"
    o.add("CfgK", sig["n_states"].default, src + " n_states")
    o.add("CfgNIter", sig["n_iter"].default, src + " n_iter")
    o.add("CfgTol", f"{sig['tol'].default:g}", src + " tol")
    o.add("CfgMinCovar", f"{sig['min_covar'].default:g}", src + " min_covar")
    o.add("CfgSigmaMin", f"{sig['sigma_min'].default:g}", src + " sigma_min")
    o.add("CfgKone", 1, "arm label: one-regime pooled probit (K = 1), bench/arms/regime.py")
    o.add("CfgKthree", 3, "arm label: K = 3, bench/results/*.json arms.k3")
    o.add("CfgKfour", 4, "variant label: K = 4, bench/results/*_variants.json scaled[k4]")
    run = (REPO / "bench" / "arms" / "run.py").read_text()
    o.add("CfgFolds", re.search(r"BlockedKFold\((\d+)\)", run).group(1), "bench/arms/run.py: BlockedKFold(n)")
    o.add("CfgBoot", f"{inspect.signature(stats.paired).parameters['n_boot'].default:,}", "bench/core/stats.py: paired n_boot")
    o.add("CfgBins", inspect.signature(stats.ece).parameters["bins"].default, "bench/core/stats.py: ece bins")
    tf = inspect.signature(fx.make).parameters["test_frac"].default
    o.add("CfgTestPct", f"{tf * 100:.0f}", "bench/data/fx.py: make test_frac (same in equities.py, m4.py)")
    o.add("CfgTrainPct", f"{(1 - tf) * 100:.0f}", "100 - held-out share")
    yrs = inspect.signature(fx.make).parameters["years"].default
    o.add("CfgFxYearA", yrs.start, "bench/data/fx.py: make years start")
    o.add("CfgFxYearB", yrs.stop - 1, "bench/data/fx.py: make years end")
    o.add("CfgFxEdges", ", ".join(map(str, fx.EDGES)), "bench/data/fx.py: EDGES (minutes)")
    o.add("CfgFxH", fx.HORIZON, "bench/data/fx.py: HORIZON (minutes)")
    o.add("CfgFxPip", max(fx.PIPS), "bench/data/fx.py: PIPS (+-)")
    o.add("CfgEqEdges", ", ".join(map(str, equities.EDGES)), "bench/data/equities.py: EDGES (days)")
    o.add("CfgEqH", equities.HORIZON, "bench/data/equities.py: HORIZON (days)")
    o.add("CfgEqPct", f"{max(equities.U) * 100:.0f}", "bench/data/equities.py: U (+- percent)")
    o.add("CfgEqEvery", inspect.signature(equities.make).parameters["every"].default, "bench/data/equities.py: make every")
    eqm = json.loads((results / "eq.json").read_text())["meta"]
    o.add("CfgEqTickers", len(eqm["tickers"]), "bench/results/eq.json: meta.tickers (count)")
    o.add("CfgEqYearA", 2005, "bench/data/equities.py: URL period1=1104537600 (2005-01-01)")
    o.add("CfgEqYearB", 2024, "bench/data/equities.py: URL period2=1735689600 (2025-01-01, last year 2024)")
    o.add("CfgMfEdges", ", ".join(map(str, m4.EDGES)), "bench/data/m4.py: EDGES (hours)")
    o.add("CfgMfHa", m4.HORIZONS[0], "bench/data/m4.py: HORIZONS[0] (hours)")
    o.add("CfgMfHb", m4.HORIZONS[1], "bench/data/m4.py: HORIZONS[1] (hours)")
    o.add("CfgMfC", f"{max(m4.C):g}", "bench/data/m4.py: C (+-)")
    o.add("CfgMfEvery", inspect.signature(m4.make).parameters["every"].default, "bench/data/m4.py: make every")
    o.add("CfgNData", 3, "bench/results/{fx,eq,m4}.json (count of datasets)")
    arms = json.loads((results / "fx.json").read_text())["arms"]
    o.add("CfgNArms", len(arms), "bench/results/fx.json: arms (count, pre-registered main run)")
    vj = json.loads((results / "fx_variants.json").read_text())
    nvar = len(vj["scaled"]) + 1
    o.add("CfgNVariants", nvar, "bench/results/fx_variants.json: len(scaled) + small_n (post-hoc variants)")
    o.add("CfgNPostCmp", nvar * 3, "post-hoc variants x 3 datasets")
    o.add("CfgSmallA", vj["small_n"][0]["n_train"], "bench/results/fx_variants.json: small_n[0].n_train")
    o.add("CfgSmallB", f"{vj['small_n'][1]['n_train']:,}", "bench/results/fx_variants.json: small_n[1].n_train")
    o.add("CfgSmallC", f"{vj['small_n'][2]['n_train']:,}", "bench/results/fx_variants.json: small_n[2].n_train")
    rep = (REPO / "regimix" / "diagnostics" / "report.py").read_text()
    o.add("CfgDwellMin", re.search(r'st\["dwell"\]\.min\(\) < (\d+)', rep).group(1), "regimix/diagnostics/report.py: dwell warning")
    o.add("CfgSpreadMin", re.search(r'st\["spread_ratio"\] < (\d+)', rep).group(1), "regimix/diagnostics/report.py: spread warning")
    o.add("CfgReproMinCovar", "10^{-3}", "patches/hmmlearn/0001-*.patch header: min_covar=1e-3")
    o.add("CfgReproSd", "0.5", "patches/hmmlearn/0001-*.patch header: round(N(0, 0.5^2))")
    o.add("CfgReproSeqs", "4,000", "patches/hmmlearn/0001-*.patch header: 4000 sequences")
    o.add("CfgReproLen", 7, "patches/hmmlearn/0001-*.patch header: length 7")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=REPO / "bench" / "results")
    ap.add_argument("--preds", type=Path, default=REPO.parent / "_data" / "regimix_predictions")
    ap.add_argument("--out", type=Path, default=HERE / "numbers.tex")
    a = ap.parse_args()
    sys.path.insert(0, str(REPO))
    from bench.core.stats import paired  # the repo's own estimator, so recomputed SEs are comparable

    o = Out()
    for key, (fname, dsname, mode) in DS.items():
        js = json.loads((a.results / f"{fname}.json").read_text())
        npz = np.load(a.preds / f"{dsname}_test_logits.npz")
        main_numbers(o, key, fname, js, npz, mode, paired)
        variant_numbers(o, key, fname, json.loads((a.results / f"{fname}_variants.json").read_text()))
        o.lines.append("")
    config_numbers(o, a.results)
    o.lines.append("")
    patch = REPO / "patches" / "hmmlearn" / "0001-gaussianhmm-apply-min-covar-after-every-m-step.patch"
    head = " ".join(patch.read_text().split("\n\n---")[0].split())
    mt = re.search(r"variances \[([\d.e-]+), ([\d.e-]+)\], ([\d.]+) x the floor", head)
    src = f"patches/hmmlearn/{patch.name}: header repro (stock GaussianHMM, min_covar 1e-3)"
    o.add("ReproVarBig", mt.group(1), src + ", larger fitted variance")
    o.add("ReproVarSmall", mt.group(2), src + ", collapsed variance")
    o.add("ReproFloorFrac", mt.group(3), src + ", collapsed variance / min_covar")
    o.add("ReproZeroShare", re.search(r"about (\d+) % exact zeros", head).group(1), src + ", share of exact zeros")
    line = (a.results / "PRIVATE_LINE.txt").read_text().strip().replace("%", "\\%").replace("~", "")
    o.add("PrivateLine", line, "bench/results/PRIVATE_LINE.txt (the only allowed sentence on the non-public task)")
    a.out.write_text("\n".join(o.lines) + "\n")
    print(f"wrote {a.out}: {sum(l.startswith(chr(92)) for l in o.lines)} macros")


if __name__ == "__main__":
    main()
